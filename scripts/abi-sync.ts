// pnpm abi:sync: after `forge build --root contracts`, regenerate src/chain/abi.ts (ABI + bytecode, `as const`).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const root = fileURLToPath(new URL("..", import.meta.url));
export const ARTIFACT_PATH = `${root}contracts/out/VekilPolicy.sol/VekilPolicy.json`;
const OUT_PATH = `${root}src/chain/abi.ts`;

const ArtifactSchema = z.object({
  abi: z.array(z.record(z.string(), z.unknown())),
  bytecode: z.object({ object: z.string().regex(/^0x[0-9a-f]+$/) }),
});

export function renderAbiModule(artifactJson: string): string {
  const a = ArtifactSchema.parse(JSON.parse(artifactJson));
  return [
    "// GENERATED by `pnpm abi:sync` from contracts/out/VekilPolicy.sol/VekilPolicy.json. Do not edit.",
    `export const vekilPolicyAbi = ${JSON.stringify(a.abi, null, 2)} as const;`,
    "",
    `export const vekilPolicyBytecode = "${a.bytecode.object}" as const;`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT_PATH, renderAbiModule(readFileSync(ARTIFACT_PATH, "utf8")));
  console.log(`abi:sync → ${OUT_PATH}`);
}
